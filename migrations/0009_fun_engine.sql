-- Fun Engine definitions remain in typed code. No historical replay in SQL.
CREATE TABLE PlayerAchievement (
 Id TEXT PRIMARY KEY, GroupId TEXT NOT NULL REFERENCES "Group"(Id) ON DELETE CASCADE,
 PlayerId TEXT NOT NULL, AchievementId TEXT NOT NULL, UnlockedAt TEXT NOT NULL,
 TriggerSessionId TEXT REFERENCES Session(Id) ON DELETE SET NULL,
 TriggerDayRecordId TEXT REFERENCES DayRecord(Id) ON DELETE SET NULL,
 IsBackfilled INTEGER NOT NULL CHECK(IsBackfilled IN (0,1)), MetadataJson TEXT,
 CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, RevokedAt TEXT,
 FOREIGN KEY(PlayerId,GroupId) REFERENCES Player(Id,GroupId) ON DELETE CASCADE,
 UNIQUE(PlayerId,AchievementId)
);
CREATE TABLE GroupAchievement (
 Id TEXT PRIMARY KEY, GroupId TEXT NOT NULL REFERENCES "Group"(Id) ON DELETE CASCADE,
 AchievementId TEXT NOT NULL, UnlockedAt TEXT NOT NULL,
 TriggerSessionId TEXT REFERENCES Session(Id) ON DELETE SET NULL,
 TriggerDayRecordId TEXT REFERENCES DayRecord(Id) ON DELETE SET NULL,
 IsBackfilled INTEGER NOT NULL CHECK(IsBackfilled IN (0,1)), MetadataJson TEXT,
 CreatedAt TEXT NOT NULL, UpdatedAt TEXT NOT NULL, RevokedAt TEXT,
 UNIQUE(GroupId,AchievementId)
);
CREATE TABLE GroupActivity (
 Id TEXT PRIMARY KEY, GroupId TEXT NOT NULL REFERENCES "Group"(Id) ON DELETE CASCADE,
 Type TEXT NOT NULL CHECK(Type IN ('PLAYER_ACHIEVEMENT_UNLOCKED','GROUP_ACHIEVEMENT_UNLOCKED','PLAYER_RECORD_BROKEN','ACHIEVEMENT_BACKFILL_SUMMARY','HIGHLIGHT_CREATED')),
 ActorUserId TEXT REFERENCES UserAccount(Id) ON DELETE SET NULL,
 PlayerId TEXT REFERENCES Player(Id) ON DELETE SET NULL, AchievementId TEXT,
 SessionId TEXT REFERENCES Session(Id) ON DELETE SET NULL,
 HighlightId TEXT REFERENCES Highlight(Id) ON DELETE SET NULL,
 CreatedAt TEXT NOT NULL, MetadataJson TEXT, InvalidatedAt TEXT
);
CREATE INDEX GroupActivity_Feed ON GroupActivity(GroupId,InvalidatedAt,CreatedAt DESC,Id DESC);
CREATE TABLE GroupActivityReadState (
 GroupId TEXT NOT NULL REFERENCES "Group"(Id) ON DELETE CASCADE,
 UserId TEXT NOT NULL REFERENCES UserAccount(Id) ON DELETE CASCADE,
 LastSeenActivityAt TEXT NOT NULL, LastSeenActivityId TEXT NOT NULL, UpdatedAt TEXT NOT NULL,
 PRIMARY KEY(GroupId,UserId)
);
CREATE TABLE PlayerFunProfile (
 PlayerId TEXT PRIMARY KEY REFERENCES Player(Id) ON DELETE CASCADE,
 MottoQuoteId TEXT, UpdatedAt TEXT NOT NULL
);
CREATE TABLE UserQuoteFavorite (
 UserId TEXT NOT NULL REFERENCES UserAccount(Id) ON DELETE CASCADE,
 QuoteId TEXT NOT NULL, CreatedAt TEXT NOT NULL, PRIMARY KEY(UserId,QuoteId)
);
CREATE TABLE ClosedMonthEvaluationState (
 GroupId TEXT NOT NULL REFERENCES "Group"(Id) ON DELETE CASCADE,
 Month TEXT NOT NULL, EvaluatedAt TEXT NOT NULL, PRIMARY KEY(GroupId,Month)
);
CREATE TABLE FunEngineState (
 GroupId TEXT PRIMARY KEY REFERENCES "Group"(Id) ON DELETE CASCADE,
 SourceSignature TEXT NOT NULL, LocalDate TEXT NOT NULL, ProjectionJson TEXT NOT NULL,
 Dirty INTEGER NOT NULL DEFAULT 0 CHECK(Dirty IN (0,1)), UpdatedAt TEXT NOT NULL
);
CREATE TABLE FunSessionProvenance (
 SessionId TEXT PRIMARY KEY REFERENCES Session(Id) ON DELETE CASCADE,
 GroupId TEXT NOT NULL REFERENCES "Group"(Id) ON DELETE CASCADE,
 SourceSessionId TEXT REFERENCES Session(Id) ON DELETE SET NULL,
 PlayerId TEXT NOT NULL REFERENCES Player(Id) ON DELETE CASCADE,
 ActorUserId TEXT NOT NULL REFERENCES UserAccount(Id) ON DELETE CASCADE, CreatedAt TEXT NOT NULL
);
CREATE TABLE FunPlayerIdentity (
 PlayerId TEXT NOT NULL REFERENCES Player(Id) ON DELETE CASCADE,
 UserId TEXT NOT NULL REFERENCES UserAccount(Id) ON DELETE CASCADE,
 PRIMARY KEY(PlayerId,UserId)
);
CREATE TABLE FunSourceObservation (
 GroupId TEXT NOT NULL REFERENCES "Group"(Id) ON DELETE CASCADE,
 SourceId TEXT NOT NULL, PRIMARY KEY(GroupId,SourceId)
);
